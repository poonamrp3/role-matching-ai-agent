"""Extract candidate text from already approved Gmail submission references."""

from __future__ import annotations

import os
from typing import Any

from role_matching.tools.gmail_candidate_submissions import (
    GmailCandidateSubmissionTool,
    GmailConnectionRequired,
    GmailCredentialStore,
)
from role_matching.workflows.nodes.gmail_retrieval import (
    DEFAULT_GMAIL_CONNECTION_ID,
    DEFAULT_GMAIL_SUBMISSIONS_LABEL,
    GMAIL_CONNECTION_ID_ENV,
    GMAIL_SUBMISSIONS_LABEL_ENV,
)
from role_matching.workflows.state import RoleMatchingState


def candidate_text_extraction_node(state: RoleMatchingState) -> dict[str, Any]:
    """Extract body and allowed attachment text for references generated by this graph run.

    Raw candidate text is returned only in ``candidate_documents`` for the immediate next local
    node. The terminal runner must use ``candidate_extraction_summary`` instead.
    """

    references = state.get("submission_references", [])
    if not references:
        return {
            "candidate_documents": [],
            "candidate_extraction_summary": [],
            "workflow_events": [
                *state.get("workflow_events", []),
                "No submission references were available for candidate-text extraction.",
            ],
        }

    label = os.getenv(GMAIL_SUBMISSIONS_LABEL_ENV, DEFAULT_GMAIL_SUBMISSIONS_LABEL)
    connection_id = os.getenv(GMAIL_CONNECTION_ID_ENV, DEFAULT_GMAIL_CONNECTION_ID)
    tool = GmailCandidateSubmissionTool(
        label=label,
        credential_store=GmailCredentialStore(connection_id=connection_id),
    )
    candidate_documents: list[dict[str, Any]] = []
    summaries: list[dict[str, Any]] = []
    errors: list[dict[str, str]] = []

    for reference in references:
        submission_id = reference["submission_id"]
        try:
            extracted = tool.extract_candidate_text(submission_id)
            candidate_documents.append(
                {
                    "submission_id": extracted.submission_id,
                    "candidate_text": extracted.candidate_text,
                    "attachment_count": extracted.attachment_count,
                }
            )
            summaries.append(
                {
                    "submission_id": extracted.submission_id,
                    "attachment_count": extracted.attachment_count,
                    "characters_extracted": len(extracted.candidate_text),
                    "extraction_status": "completed",
                }
            )
        except GmailConnectionRequired as error:
            return {
                "gmail_connection_ok": False,
                "status": "failed",
                "candidate_documents": candidate_documents,
                "candidate_extraction_summary": summaries,
                "candidate_extraction_errors": [
                    *errors,
                    {"submission_id": submission_id, "error": str(error)},
                ],
                "validation_errors": [*state.get("validation_errors", []), str(error)],
                "workflow_events": [
                    *state.get("workflow_events", []),
                    "Candidate-text extraction stopped because Gmail needs reconnection.",
                ],
            }
        except Exception as error:
            errors.append({"submission_id": submission_id, "error": str(error)})

    if not candidate_documents:
        return {
            "status": "failed",
            "candidate_documents": [],
            "candidate_extraction_summary": summaries,
            "candidate_extraction_errors": errors,
            "validation_errors": [
                *state.get("validation_errors", []),
                "No candidate text could be extracted from the retrieved submissions.",
            ],
            "workflow_events": [*state.get("workflow_events", []), "Candidate-text extraction failed."],
        }

    return {
        "candidate_documents": candidate_documents,
        "candidate_extraction_summary": summaries,
        "candidate_extraction_errors": errors,
        "workflow_events": [
            *state.get("workflow_events", []),
            f"Extracted candidate text for {len(candidate_documents)} submission(s).",
        ],
    }
